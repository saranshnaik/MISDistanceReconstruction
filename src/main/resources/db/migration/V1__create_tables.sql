-- Every table carries tenant_id so one client's rows can never be mixed up with another's.
-- Distances in the computation table are whole millimetres, same as the engine.

create table trip (
    id                      bigint generated by default as identity primary key,
    tenant_id               varchar(64)  not null,
    trip_ref                varchar(128) not null,
    trip_type               varchar(16)  not null,
    trip_start              timestamp with time zone not null,
    trip_end                timestamp with time zone not null,
    actual_start_lat        double precision,
    actual_start_lon        double precision,
    actual_end_lat          double precision,
    actual_end_lon          double precision,
    office_lat              double precision not null,
    office_lon              double precision not null,
    distance_state          varchar(16)  not null,
    billing_state           varchar(16)  not null,
    current_computation_id  bigint,
    billed_km               numeric(12, 2),
    billed_computation_id   bigint,
    created_at              timestamp with time zone not null,
    constraint uq_trip_tenant_ref unique (tenant_id, trip_ref)
);

-- the background job looks for DEGRADED trips
create index idx_trip_distance_state on trip (distance_state);

create table trip_stop (
    id              bigint generated by default as identity primary key,
    tenant_id       varchar(64)  not null,
    trip_id         bigint       not null references trip (id),
    employee_ref    varchar(128) not null,
    rider_type      varchar(16)  not null,
    event           varchar(16)  not null,
    actual_lat      double precision,
    actual_lon      double precision,
    actual_time     timestamp with time zone,
    planned_lat     double precision,
    planned_lon     double precision,
    planned_time    timestamp with time zone,
    home_lat        double precision,
    home_lon        double precision,
    sign_in_time    timestamp with time zone
);

create index idx_trip_stop_trip on trip_stop (trip_id);

create table ping (
    id           bigint generated by default as identity primary key,
    tenant_id    varchar(64) not null,
    trip_id      bigint      not null references trip (id),
    recorded_at  timestamp with time zone not null,
    lat          double precision not null,
    lon          double precision not null,
    accuracy_m   double precision,
    received_at  timestamp with time zone not null,
    -- the same reading sent twice is stored once
    constraint uq_ping_reading unique (trip_id, recorded_at, lat, lon)
);

create table distance_computation (
    id              bigint generated by default as identity primary key,
    tenant_id       varchar(64) not null,
    trip_id         bigint      not null references trip (id),
    input_hash      varchar(64) not null,
    rule_version    varchar(32) not null,
    total_mm        bigint      not null,
    billable_km     numeric(12, 2) not null,
    status          varchar(16) not null,
    route_requests  integer     not null,
    provider_calls  integer     not null,
    cache_hits      integer     not null,
    segments_json   text        not null,
    computed_at     timestamp with time zone not null
);

create index idx_computation_trip on distance_computation (trip_id);

-- A signed correction (+1.80 km, -0.40 km) instead of editing a closed invoice.
create table billing_adjustment (
    id              bigint generated by default as identity primary key,
    tenant_id       varchar(64) not null,
    trip_id         bigint      not null references trip (id),
    computation_id  bigint      not null references distance_computation (id),
    delta_km        numeric(12, 2) not null,
    reason          varchar(255) not null,
    created_at      timestamp with time zone not null,
    -- one computation can only ever produce one adjustment
    constraint uq_adjustment_computation unique (computation_id)
);

create index idx_adjustment_trip on billing_adjustment (trip_id);
